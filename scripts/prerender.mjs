#!/usr/bin/env node
/**
 * Writes one HTML file per public page (and language) into dist/, each with its own title, description,
 * canonical, hreflang, link-preview tags and structured data, then regenerates dist/sitemap.xml.
 *
 * Run after `vite build` and `vite build --ssr src/seo/prerender.ts --outDir dist-ssr` (see "build" in package.json).
 * The page body is still rendered by React in the browser; only <head> changes, so the site looks the same.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const distDir = path.join(root, "dist");
const ssrEntry = path.join(root, "dist-ssr", "prerender.js");
const SITE_ORIGIN = "https://busystrong90.com";

const PAGE_START = /<!-- seo:page:start[\s\S]*?<!-- seo:page:end -->/;
const HOME_ONLY = /[ \t]*<!-- seo:home-only:start -->[\s\S]*?<!-- seo:home-only:end -->\r?\n?/;
const HTML_OPEN = /<html\b[^>]*>/;

function escapeAttr(value) {
  return String(value).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function escapeText(value) {
  return String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** JSON inside <script> must not contain "</" or the script would end early. */
function safeJson(value) {
  return JSON.stringify(value).replace(/</g, "\\u003c");
}

function renderHead(head) {
  const lines = ["<!-- seo:page:start — generated by scripts/prerender.mjs -->", `<title>${escapeText(head.title)}</title>`];
  for (const { tag, attrs } of head.tags) {
    const attrText = Object.entries(attrs)
      .map(([key, value]) => `${key}="${escapeAttr(value)}"`)
      .join(" ");
    lines.push(tag === "meta" ? `<meta data-rh="true" ${attrText} />` : `<link data-rh="true" ${attrText} />`);
  }
  for (const schema of head.jsonLd) {
    lines.push(`<script data-rh="true" type="application/ld+json">${safeJson(schema)}</script>`);
  }
  lines.push("<!-- seo:page:end -->");
  return lines.join("\n    ");
}

function htmlOpenTag(lang) {
  return lang === "ar" ? `<html lang="ar" dir="rtl" class="dark">` : `<html lang="${lang}" class="dark">`;
}

function outputFile(url) {
  if (url === "/") return path.join(distDir, "index.html");
  return path.join(distDir, ...url.split("/").filter(Boolean), "index.html");
}

function renderSitemap(pages) {
  const entries = pages
    .filter((page) => page.sitemap)
    .map((page) => {
      const loc = `${SITE_ORIGIN}${page.url}`;
      const alternates = page.sitemap.alternates
        .map((alt) => `\n    <xhtml:link rel="alternate" hreflang="${alt.hreflang}" href="${escapeAttr(alt.href)}" />`)
        .join("");
      const lastmod = page.sitemap.lastmod ? `\n    <lastmod>${page.sitemap.lastmod.slice(0, 10)}</lastmod>` : "";
      return `  <url>\n    <loc>${escapeText(loc)}</loc>${lastmod}${alternates}\n  </url>`;
    });
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated at build time by scripts/prerender.mjs from the site\'s pages and blog posts. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
    ...entries,
    "</urlset>",
    "",
  ].join("\n");
}

async function main() {
  const template = await readFile(path.join(distDir, "index.html"), "utf8");
  if (!PAGE_START.test(template)) throw new Error("dist/index.html has no <!-- seo:page:start --> block; check index.html.");
  if (!HOME_ONLY.test(template)) throw new Error("dist/index.html has no <!-- seo:home-only:start --> block; check index.html.");

  const { getPrerenderPages } = await import(pathToFileURL(ssrEntry).href);
  const pages = getPrerenderPages();
  const seen = new Set();

  for (const page of pages) {
    if (seen.has(page.url)) throw new Error(`Duplicate prerender URL: ${page.url}`);
    seen.add(page.url);

    let html = template.replace(PAGE_START, () => renderHead(page.head)).replace(HTML_OPEN, htmlOpenTag(page.head.lang));
    if (!page.preloadHero) html = html.replace(HOME_ONLY, "");

    const file = outputFile(page.url);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, html, "utf8");
  }

  await writeFile(path.join(distDir, "sitemap.xml"), renderSitemap(pages), "utf8");
  const inSitemap = pages.filter((page) => page.sitemap).length;
  console.log(`prerender: wrote ${pages.length} pages (${inSitemap} in sitemap.xml)`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
